#!/usr/bin/env node
// ============================================================
// PoseArt Solarize — inject test credentials (defect D16/D22/D23 fix)
// ------------------------------------------------------------
// Reads POSEART_TEST_USERNAME / POSEART_TEST_PASSWORD from the
// environment (set via protected CI secrets — NEVER committed)
// and writes a NON-COMMITTED `js/test-creds.local.js` that
// installs `window.__POSEART_TEST_CREDENTIALS__`.
//
// `js/test-creds.local.js` is listed in `.gitignore`. This script
// MUST NOT print the credential values — only the env var NAMES
// are referenced in logs.
//
// Usage:
//   POSEART_TEST_USERNAME=... POSEART_TEST_PASSWORD=... \
//     node scripts/inject-test-creds.js
//
// Exit codes:
//   0  — bundle written successfully
//   2  — required env var(s) missing (fails closed, no file written)
//   3  — filesystem write error
// ============================================================
'use strict';

import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const username = process.env.POSEART_TEST_USERNAME;
const password = process.env.POSEART_TEST_PASSWORD;

if (!username || !password) {
  console.error('[inject-test-creds] POSEART_TEST_USERNAME and POSEART_TEST_PASSWORD must both be set.');
  console.error('[inject-test-creds] Refusing to write js/test-creds.local.js — login gate stays closed.');
  console.error('[inject-test-creds] Source: CI secrets (env var names only — values never logged).');
  process.exit(2);
}

const outFile = resolve(__dirname, '..', 'js', 'test-creds.local.js');

// Escape backslashes and single quotes for safe JS single-quoted string embedding.
function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const payload =
  '// AUTO-GENERATED by scripts/inject-test-creds.js — DO NOT COMMIT.\n' +
  '// Source: CI secret POSEART_TEST_USERNAME / POSEART_TEST_PASSWORD.\n' +
  '// This file is gitignored. It is rebuilt on every CI run and never\n' +
'// checked into version control. Credential values are not logged.\n' +
  '(function (global) {\n' +
  "  global.__POSEART_TEST_CREDENTIALS__ = Object.freeze({\n" +
  "    users: [{ u: '" + esc(username) + "', p: '" + esc(password) + "' }],\n" +
  '    sessionOnly: true,\n' +
  '  });\n' +
  "})(typeof window !== 'undefined' ? window : globalThis);\n";

try {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, payload, { mode: 0o600 });
} catch (e) {
  console.error('[inject-test-creds] Failed to write js/test-creds.local.js:', e.message);
  process.exit(3);
}

if (existsSync(outFile)) {
  console.log('[inject-test-creds] Wrote js/test-creds.local.js (credential values not printed).');
} else {
  console.error('[inject-test-creds] Verification failed — file not present after write.');
  process.exit(3);
}
